def build_terms() -> list[dict]:
    out: list[dict] = []
    for i, row in enumerate(TERMS):
        slug, title, short_def, why, example, category, track, related, aliases, keywords = row
        out.append({
            "id": slug,
            "slug": slug,
            "title": title,
            "shortDefinition": short_def,
            "whyItMatters": why,
            "example": example,
            "category": category,
            "track": track,
            "relatedConceptSlugs": related,
            "aliases": aliases,
            "keywords": keywords,
            "sortOrder": i + 1,
        })
    return out


def main() -> None:
    terms = build_terms()
    OUTPUT.write_text(json.dumps(terms, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {len(terms)} terms to {OUTPUT}")


if __name__ == "__main__":
    main()
